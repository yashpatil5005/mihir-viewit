#!/usr/bin/env node
import { createHash } from "node:crypto";
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { parseProviderDescriptorV1, parseServiceDescriptorV1 } from "../packages/contracts/src/index.ts";

const root = resolve(import.meta.dirname, "..");
const services = JSON.parse(readFileSync(resolve(root, "packages/contracts/catalog/services.v1.json"), "utf8")).map(parseServiceDescriptorV1);
const providers = JSON.parse(readFileSync(resolve(root, "packages/contracts/catalog/providers.v1.json"), "utf8")).map(parseProviderDescriptorV1);
const canonical = JSON.stringify({ services, providers });
const fingerprint = createHash("sha256").update(canonical).digest("hex");
const quote = (value) => JSON.stringify(value);

const kotlin = `// Generated by scripts/generate-contract-projections.mjs. Do not edit.
package ai.viewit.app

object ViewItContractCatalog {
    const val FINGERPRINT = ${quote(fingerprint)}
    val serviceIds = listOf(${services.map((item) => quote(item.id)).join(", ")})
    val providers = listOf(
${providers.map((item) => `        ProviderContract(${quote(item.id)}, ${quote(item.packageId)}, ${quote(item.service)}, ${item.contractVersion}, ${quote(item.runtime)}, ${quote(item.trustClass)})`).join(",\n")}
    )
}

data class ProviderContract(
    val id: String,
    val packageId: String,
    val service: String,
    val contractVersion: Int,
    val runtime: String,
    val trustClass: String,
)
`;

const rust = `// Generated by scripts/generate-contract-projections.mjs. Do not edit.
pub const CONTRACT_CATALOG_FINGERPRINT: &str = ${quote(fingerprint)};
pub const SERVICE_IDS: &[&str] = &[${services.map((item) => quote(item.id)).join(", ")}];

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct ProviderContract {
    pub id: &'static str,
    pub package_id: &'static str,
    pub service: &'static str,
    pub contract_version: u32,
    pub runtime: &'static str,
    pub trust_class: &'static str,
}

pub const PROVIDERS: &[ProviderContract] = &[
${providers.map((item) => `    ProviderContract { id: ${quote(item.id)}, package_id: ${quote(item.packageId)}, service: ${quote(item.service)}, contract_version: ${item.contractVersion}, runtime: ${quote(item.runtime)}, trust_class: ${quote(item.trustClass)} },`).join("\n")}
];
`;

const outputs = [
  [resolve(root, "apps/mobile/src-tauri/android/ViewItContractCatalog.generated.kt"), kotlin],
  [
    resolve(root, "crates/core-types/src/contracts_generated.rs"),
    execFileSync("rustfmt", ["--emit", "stdout"], { input: rust, encoding: "utf8" }),
  ],
];
const check = process.argv.includes("--check");
let changed = false;
for (const [path, content] of outputs) {
  const current = (() => { try { return readFileSync(path, "utf8"); } catch { return ""; } })();
  if (current === content) continue;
  changed = true;
  if (!check) writeFileSync(path, content);
  console.error(`[contracts] ${check ? "stale" : "generated"}: ${path.replace(root + "/", "")}`);
}
if (check && changed) process.exit(1);
console.log(`[contracts] projection fingerprint ${fingerprint}`);
