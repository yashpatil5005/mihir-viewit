/** Extensions whose web render is delivered by the WASM fmt-* crates. */
const EBOOK_EXT = new Set(["epub", "mobi", "azw3"]);
const IWORK_EXT = new Set(["pages", "numbers", "key"]);

/** Deterministic classification of one normalized extension. */
export function webRouteKind(ext: string): WebRouteKind {
  const e = (ext ?? "").trim().toLowerCase().replace(/^\./, "");
  if (!e) return "placeholder";
  if (OFFICE_EXT.has(e)) return "office";
  if (ARCHIVE_EXT.has(e)) return "archive";
  if (IWORK_EXT.has(e)) return "iwork";
  if (EBOOK_EXT.has(e)) return "ebook";
  if (e === "pdf") return "pdf";
  if (FONT_EXT.has(e)) return "font";
  if (AUDIO_EXT.has(e)) return "audio";
  if (VIDEO_EXT.has(e)) return "video";
  if (IMAGE_EXT.has(e)) return "image";
  if (TEXT_EXT.has(e)) return "text";
  return "placeholder";
}

export { OFFICE_EXT, ARCHIVE_EXT, IMAGE_EXT, FONT_EXT, AUDIO_EXT, VIDEO_EXT, TEXT_EXT };
